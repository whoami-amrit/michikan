import type { IFinding } from './snapshot';
import type { FindingIssueCodeType } from './types';

const HIGH_SEVERITY_PENALTY = 10;
const MEDIUM_SEVERITY_PENALTY = 5;
const LOW_SEVERITY_PENALTY = 2;

export const SCORE_WEIGHTS = Object.freeze({
  PII: HIGH_SEVERITY_PENALTY,
  UNPAID_AS_WORK: HIGH_SEVERITY_PENALTY,
  BANNED_VERB: HIGH_SEVERITY_PENALTY,
  NO_RESULT: MEDIUM_SEVERITY_PENALTY,
  VAGUE_CLAIM: MEDIUM_SEVERITY_PENALTY,
  WEAK_OWNERSHIP: MEDIUM_SEVERITY_PENALTY,
  UNJUSTIFIED_SUMMARY: MEDIUM_SEVERITY_PENALTY,
  TOOL_CENTRIC: MEDIUM_SEVERITY_PENALTY,
  PRONOUN: MEDIUM_SEVERITY_PENALTY,
  WEAK_VERB: MEDIUM_SEVERITY_PENALTY,
  OVERWROUGHT_VERB: MEDIUM_SEVERITY_PENALTY,
  HIDDEN_SKILL: LOW_SEVERITY_PENALTY,
  ORPHAN_SKILL: LOW_SEVERITY_PENALTY,
  TECH_CASING: LOW_SEVERITY_PENALTY,
  TRAILING_PERIOD: LOW_SEVERITY_PENALTY,
  SYMBOL: LOW_SEVERITY_PENALTY,
  SPELLED_NUMBER: LOW_SEVERITY_PENALTY,
  B_WORD: LOW_SEVERITY_PENALTY,
  LONG_BULLET: LOW_SEVERITY_PENALTY,
  SKILL_AMALGAM: LOW_SEVERITY_PENALTY,
  SKILL_PROFICIENCY: LOW_SEVERITY_PENALTY,
  SOFT_SKILL: LOW_SEVERITY_PENALTY,
  BASIC_SKILL: LOW_SEVERITY_PENALTY,
  GITHUB_AS_SKILL: LOW_SEVERITY_PENALTY,
  LEGACY_EMAIL: LOW_SEVERITY_PENALTY,
  PROJECT_IN_TITLE: LOW_SEVERITY_PENALTY,
} satisfies Record<FindingIssueCodeType, number>);

export const MAX_SCORE = 100;

export function computeScore(findings: readonly Pick<IFinding, 'issue'>[]): number {
  const penalty = findings.reduce((total, { issue }) => total + SCORE_WEIGHTS[issue], 0);
  return Math.max(0, MAX_SCORE - penalty);
}
